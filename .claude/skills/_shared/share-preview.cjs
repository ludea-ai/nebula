#!/usr/bin/env node
/*
 * share-preview — the card a link to the game shows when it is shared (iMessage, WhatsApp,
 * Slack, social networks): a 1200×630 image (the home splash + the logo) and the Open Graph /
 * Twitter tags in index.html, written between two markers so the rest of the file is untouched.
 * The address comes from public-url.cjs (which also checks the README's « Play » link).
 *
 *   node .claude/skills/_shared/share-preview.cjs            # from the game root
 *   node .claude/skills/_shared/share-preview.cjs --url https://example.org/my-game/
 *   node .claude/skills/_shared/share-preview.cjs --check    # exit 1 if missing or out of date
 *
 * Title "Ludea – <game title>", description = meta.tagline (source language), image =
 * assets/share.jpg. Crawlers need ABSOLUTE addresses: the game's public address comes from the
 * git remote (ludea-ai/<repo> → https://ludea.ai/<repo>/, <owner>/<repo> →
 * https://<owner>.github.io/<repo>/) unless --url is given. The image is re-rendered only when its
 * inputs (splash, logo, title, tagline) change. Run by release-deploy; checked by publish-check.
 */
"use strict";
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const ROOT = process.cwd();
const argv = process.argv.slice(2);
const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
const START = "<!-- ludea:share (generated by share-preview.cjs — do not edit by hand) -->", END = "<!-- /ludea:share -->";
const IMG = "assets/share.jpg", W = 1200, H = 630;

// the config is read in a sandboxed browser, never with node:vm (config-json.cjs)
const GAME = require("./config-json.cjs").readGlobals([[path.join(ROOT, "game.config.js"), "GAME"]]).GAME || {};
const M = GAME.meta || {};
const title = M.title || path.basename(ROOT);
const desc = M.tagline || M.description || "";
const lang = M.lang || "en";

function publicUrl() {
  const u = require("./public-url.cjs").publicUrl(ROOT, opt("--url"));
  if (!u) { console.error("share-preview: cannot tell the game's public address from the git remote — pass --url"); process.exit(2); }
  return u;
}

const file = (f) => f && fs.existsSync(path.join(ROOT, f)) ? path.join(ROOT, f) : null;
const splash = file(M.splash), logo = file(M.logo);
const hash = crypto.createHash("sha1");
for (const f of [splash, logo]) hash.update(f ? fs.readFileSync(f) : "none");
hash.update(title + "\n" + desc + "\nrender:2"); // render:N = the card's drawing rules (bump to re-render every game's card)
const key = hash.digest("hex").slice(0, 10);

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
function block(url) {
  const t = `Ludea – ${title}`, img = `${url}${IMG}?v=${key}`;
  const loc = lang === "fr" ? "fr_FR" : "en_US", alt = lang === "fr" ? "en_US" : "fr_FR";
  return [START,
    `  <meta name="description" content="${esc(desc)}" />`,
    `  <meta property="og:type" content="website" />`,
    `  <meta property="og:site_name" content="Ludea" />`,
    `  <meta property="og:title" content="${esc(t)}" />`,
    `  <meta property="og:description" content="${esc(desc)}" />`,
    `  <meta property="og:url" content="${esc(url)}" />`,
    `  <meta property="og:image" content="${esc(img)}" />`,
    `  <meta property="og:image:width" content="${W}" />`,
    `  <meta property="og:image:height" content="${H}" />`,
    `  <meta property="og:image:alt" content="${esc(title)}" />`,
    `  <meta property="og:locale" content="${loc}" />`,
    `  <meta property="og:locale:alternate" content="${alt}" />`,
    `  <meta name="twitter:card" content="summary_large_image" />`,
    `  <meta name="twitter:title" content="${esc(t)}" />`,
    `  <meta name="twitter:description" content="${esc(desc)}" />`,
    `  <meta name="twitter:image" content="${esc(img)}" />`,
    `  ${END}`].join("\n");
}

// The card uses the game's own look: its splash, its logo and its title styled by its own CSS
// (engine.css + style.css: font, --title-fill / --title-stroke), like the home screen.
async function render() {
  let pw = null;
  for (const c of ["playwright", "/opt/node22/lib/node_modules/playwright"]) { try { pw = require(c); break; } catch (e) {} }
  if (!pw) { console.error("share-preview: Playwright not found"); process.exit(2); }
  const rel = (f) => path.relative(ROOT, f).split(path.sep).join("/");
  const html = `<!doctype html><html><head><meta charset="utf-8">
    <link rel="stylesheet" href="engine.css"><link rel="stylesheet" href="style.css">
    <style>html,body{margin:0;width:${W}px;height:${H}px;overflow:hidden}
      .card{position:fixed;inset:0;display:flex;flex-direction:column;align-items:center;justify-content:center;gap:6px}
      .bg{position:fixed;inset:-12px;background:#222 ${splash ? `url('${rel(splash)}') center 38%/cover` : ""};filter:blur(3px) brightness(.85)}
      .shade{position:fixed;inset:0;background:radial-gradient(ellipse at 50% 50%,rgba(0,0,0,0) 30%,rgba(0,0,0,.45) 100%)}
      .card img{max-width:62%;max-height:${logo ? 300 : 0}px;filter:drop-shadow(0 10px 24px rgba(0,0,0,.35))}
      .card .game-title{font-size:${title.length > 22 ? 64 : 80}px;text-align:center;padding:0 40px}
      .shade2{position:fixed;left:0;right:0;bottom:0;height:42%;background:linear-gradient(rgba(0,0,0,0),rgba(0,0,0,.38))}</style></head>
    <body><div class="bg"></div><div class="shade"></div><div class="shade2"></div>
    <div class="card">${logo ? `<img id="logo" alt="">` : ""}<h1 class="game-title">${esc(title)}</h1></div></body></html>`;
  const tmp = path.join(ROOT, ".share-preview.tmp.html");
  fs.writeFileSync(tmp, html);
  try {
    const browser = await pw.chromium.launch();
    const page = await browser.newPage({ viewport: { width: W, height: H } });
    await page.goto("file://" + tmp, { waitUntil: "load" });
    // The logo, trimmed to its fully transparent margins (logos often carry empty margins).
    // Every pixel with alpha > 0 is kept, so a soft glow or shadow fades out by itself — a cut at
    // a higher alpha left a faint rectangle on the card (game-engine#17). The logo is SIZED by its
    // solid part (alpha > 24, as before), so a wide faint glow spills around it instead of
    // shrinking the drawing.
    if (logo) await page.evaluate(async ({ src, maxW, maxH }) => {
      const im = new Image(); im.src = src; await im.decode();
      const c = document.createElement("canvas"); c.width = im.naturalWidth; c.height = im.naturalHeight;
      const x = c.getContext("2d"); x.drawImage(im, 0, 0);
      const d = x.getImageData(0, 0, c.width, c.height).data;
      const all = { t: c.height, b: -1, l: c.width, r: -1 }, solid = { t: c.height, b: -1, l: c.width, r: -1 };
      const grow = (q, y, k) => { if (y < q.t) q.t = y; if (y > q.b) q.b = y; if (k < q.l) q.l = k; if (k > q.r) q.r = k; };
      for (let y = 0; y < c.height; y++) for (let k = 0; k < c.width; k++) {
        const a = d[(y * c.width + k) * 4 + 3];
        if (a > 0) grow(all, y, k);
        if (a > 24) grow(solid, y, k);
      }
      const full = { t: 0, l: 0, b: c.height - 1, r: c.width - 1 };
      const A = all.b < 0 ? full : all, S = solid.b < 0 ? A : solid;
      const o = document.createElement("canvas"); o.width = A.r - A.l + 1; o.height = A.b - A.t + 1;
      o.getContext("2d").drawImage(c, A.l, A.t, o.width, o.height, 0, 0, o.width, o.height);
      const sw = S.r - S.l + 1, sh = S.b - S.t + 1, k = Math.min(1, maxW / sw, maxH / sh); // like max-width/max-height: never enlarged
      const el = document.getElementById("logo");
      el.style.cssText = `max-width:none;max-height:none;width:${o.width * k}px;height:${o.height * k}px;` +
        // the solid part stays where the whole logo used to be: the glow overflows, the layout doesn't move
        `margin:${-(S.t - A.t) * k}px ${-(A.r - S.r) * k}px ${-(A.b - S.b) * k}px ${-(S.l - A.l) * k}px`;
      el.src = o.toDataURL(); await el.decode();
    }, { maxW: W * 0.62, maxH: 300, src: "data:image/" + path.extname(logo).slice(1).replace("jpg", "jpeg") + ";base64," + fs.readFileSync(logo).toString("base64") });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(200);
    await page.screenshot({ path: path.join(ROOT, IMG), type: "jpeg", quality: 86 });
    await browser.close();
  } finally { fs.rmSync(tmp, { force: true }); }
}

(async () => {
  const idxPath = path.join(ROOT, "index.html");
  let idx = fs.readFileSync(idxPath, "utf8");
  const url = publicUrl();
  const want = block(url);
  const re = new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[\\s\\S]*?" + END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  const cur = (idx.match(re) || [""])[0].trim();
  const upToDate = cur === want.trim() && fs.existsSync(path.join(ROOT, IMG));
  if (argv.includes("--check")) {
    console.log(upToDate ? `share preview OK (${url})` : !cur ? "no share preview in index.html — run share-preview.cjs" : "share preview out of date — run share-preview.cjs");
    process.exit(upToDate ? 0 : 1);
  }
  if (!cur.includes(`?v=${key}`) || !fs.existsSync(path.join(ROOT, IMG))) await render();
  if (cur) idx = idx.replace(re, () => want.trim());
  else idx = idx.replace(/\s*<\/head>/i, () => `\n  ${want.trim()}\n</head>`);
  fs.writeFileSync(idxPath, idx);
  console.log(`share preview: ${IMG} (${W}×${H}) + tags for ${url}`);
})().catch((e) => { console.error("share-preview failed:", e.message); process.exit(2); });
